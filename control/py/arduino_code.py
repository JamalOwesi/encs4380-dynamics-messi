"""
arduino_code.py - turns the current gains into an Arduino sketch.

The control law is the same one simulated in pid_core.DigitalPID:
  u[k] = Kp e[k] + Ki Ts sum(e[0..k]) + Kd (e[k] - e[k-1]) / Ts
with clamping anti-windup and the actuator limit, so what you see in P3 /
"My system" is what the board will run.
"""


def _f(v):
    return ("%.6g" % v) if "." in ("%.6g" % v) or "e" in ("%.6g" % v) else ("%.6g.0" % v)


_PID_BODY = """
// ---- PID state ----
float sumE  = 0.0;   // sum of e[0..k]
float prevE = 0.0;   // e[k-1], starts at 0
unsigned long lastSample = 0;

float pidUpdate(float e) {
  float sumNew = sumE + e;
  float u = Kp * e + Ki * Ts * sumNew + Kd * (e - prevE) / Ts;
  bool pushingUp   = (u > U_MAX) && (e > 0);
  bool pushingDown = (u < U_MIN) && (e < 0);
  if (ANTI_WINDUP && (pushingUp || pushingDown)) {
    sumNew = sumE;                       // freeze the integral while saturated
    u = Kp * e + Ki * Ts * sumNew + Kd * (e - prevE) / Ts;
  }
  sumE  = sumNew;
  prevE = e;
  return constrain(u, U_MIN, U_MAX);     // actuator limit
}
"""


def generate(Kp, Ki, Kd, Ts, u_min, u_max, anti_windup, setpoint,
             mode="generic", units="", counts_per_rev=None):
    ts_us = int(round(Ts * 1e6))
    head = """// Digital PID generated by the Group Messi Control Toolkit (ENCS4380 HW2)
// u[k] = Kp e[k] + Ki Ts sum e[j] + Kd (e[k]-e[k-1]) / Ts
const float Kp = %s;
const float Ki = %s;
const float Kd = %s;
const float Ts = %s;                  // sampling time [s]
const unsigned long TS_US = %dUL;     // the same, in microseconds
const float U_MIN = %s;
const float U_MAX = %s;
const bool  ANTI_WINDUP = %s;
float setpoint = %s;%s
""" % (_f(Kp), _f(Ki), _f(Kd), _f(Ts), ts_us, _f(u_min), _f(u_max),
       "true" if anti_windup else "false", _f(setpoint),
       ("                // " + units) if units else "")

    if mode == "encoder":
        io = """
// ---- Micromouse drive motor: encoder in, PWM out ----
// TODO: set the pins and counts for YOUR motor and driver.
const int ENC_A = 2;          // interrupt pin
const int ENC_B = 4;
const int PWM_PIN = 5;        // driver PWM input (for TB6612/DRV8833 also set the direction pins)
const float COUNTS_PER_REV = %s;  // encoder counts per OUTPUT-shaft revolution
const bool  STEP_TEST = false;    // true = open-loop PWM step to measure K and tau
const float STEP_PWM  = 50.0;     // PWM step size [%%] for the step test

volatile long encCount = 0;
void encISR() { if (digitalRead(ENC_B)) encCount++; else encCount--; }

// wheel speed in rpm, from the counts seen during the last sample period
float readSensor() {
  static long lastCount = 0;
  noInterrupts(); long c = encCount; interrupts();
  long d = c - lastCount;
  lastCount = c;
  return (d / COUNTS_PER_REV) / Ts * 60.0;
}

// u is the PWM duty cycle in percent (0-100)
void writeActuator(float u) {
  analogWrite(PWM_PIN, (int)(u * 255.0 / 100.0 + 0.5));
}
""" % _f(counts_per_rev or 360.0)
        setup = """
void setup() {
  pinMode(ENC_A, INPUT_PULLUP);
  pinMode(ENC_B, INPUT_PULLUP);
  pinMode(PWM_PIN, OUTPUT);
  attachInterrupt(digitalPinToInterrupt(ENC_A), encISR, RISING);
  Serial.begin(115200);
  Serial.println("t,setpoint,speed,u");   // paste this log into the 'My system' fit tool
  lastSample = micros();
}
"""
        loop = """
void loop() {
  if (micros() - lastSample >= TS_US) {
    lastSample += TS_US;                 // fixed rate: no drift
    static unsigned long k = 0;
    float t = k * Ts;
    float y = readSensor();
    float u;
    if (STEP_TEST) {
      u = (t >= 0.5) ? STEP_PWM : 0.0;   // step at t = 0.5 s
    } else {
      u = pidUpdate(setpoint - y);
    }
    writeActuator(u);
    Serial.print(t, 3); Serial.print(',');
    Serial.print(setpoint); Serial.print(',');
    Serial.print(y); Serial.print(',');
    Serial.println(u);
    k++;
  }
}
"""
    else:
        io = """
// ---- I/O: change these two functions for your sensor and actuator ----
const int SENSOR_PIN = A0;
const int PWM_PIN = 9;

float readSensor() {
  // TODO: convert to the same units as the setpoint
  return analogRead(SENSOR_PIN) * (5.0 / 1023.0);
}

void writeActuator(float u) {
  // maps U_MIN..U_MAX to PWM 0..255
  int duty = (int)(255.0 * (u - U_MIN) / (U_MAX - U_MIN) + 0.5);
  analogWrite(PWM_PIN, duty);
}
"""
        setup = """
void setup() {
  pinMode(PWM_PIN, OUTPUT);
  Serial.begin(115200);
  lastSample = micros();
}
"""
        loop = """
void loop() {
  if (micros() - lastSample >= TS_US) {  // run exactly every Ts
    lastSample += TS_US;
    float y = readSensor();
    float u = pidUpdate(setpoint - y);
    writeActuator(u);
    Serial.print(y); Serial.print(','); Serial.println(u);
  }
}
"""
    return head + io + _PID_BODY + setup + loop
